suppressPackageStartupMessages({library(edgeR);library(data.table)})
base<-commandArgs(trailingOnly=TRUE)[1]
states<-c('c03_CD4_Tn_NR4A2','c08_CD4_Tfh_CXCL13_IL6ST','c20_CD8_Tem_GZMK','c27_CD8_MAIT_SLC4A10')
audits<-list()
for(state in states){
 d<-file.path(base,'inputs',state)
 raw<-fread(cmd=paste('gzip -dc',shQuote(file.path(d,'counts.tsv.gz'))),data.table=FALSE)
 counts<-as.matrix(raw[,-1]);rownames(counts)<-raw[[1]];rm(raw)
 meta<-fread(file.path(d,'samples.tsv'),data.table=FALSE)
 stopifnot(identical(colnames(counts),meta$sample_id))
 meta$donor<-factor(meta$patient_id);meta$condition<-factor(meta$condition,levels=c('rest','target'))
 stopifnot(all(table(meta$donor)==2),nlevels(meta$donor)>=6)
 y<-DGEList(counts=counts);design<-model.matrix(~donor+condition,data=meta)
 stopifnot(qr(design)$rank==ncol(design))
 keep<-filterByExpr(y,group=meta$condition,min.count=10,min.total.count=15,large.n=10,min.prop=.7)
 y<-y[keep,,keep.lib.sizes=FALSE];y<-normLibSizes(y,method='TMM');y<-estimateDisp(y,design,robust=TRUE)
 fit<-glmQLFit(y,design,robust=TRUE,legacy=FALSE);test<-glmQLFTest(fit,coef='conditiontarget')
 tab<-topTags(test,n=Inf,sort.by='none')$table;tab$gene<-rownames(tab)
 lc<-cpm(y,log=TRUE,prior.count=2)
 delta<-sapply(levels(meta$donor),function(d)lc[,meta$patient_id==d&meta$condition=='target']-lc[,meta$patient_id==d&meta$condition=='rest'])
 colnames(delta)<-levels(meta$donor)
 tab$donor_direction_fraction<-rowMeans(delta>0);tab$n_paired_donors<-nlevels(meta$donor)
 tab$mean_donor_logCPM_difference<-rowMeans(delta)
 tab$min_leave_one_donor_out_mean_difference<-apply((rowSums(delta)-delta)/(ncol(delta)-1),1,min)
 tab$state<-state
 write.table(tab,file.path(base,'de',paste0(state,'.tsv')),sep='\t',row.names=FALSE,quote=FALSE)
 write.table(data.frame(gene=rownames(delta),delta),file.path(base,'de',paste0(state,'_donor_differences.tsv')),sep='\t',row.names=FALSE,quote=FALSE)
 write.table(data.frame(sample_id=rownames(y$samples),y$samples),file.path(base,'de',paste0(state,'_normalization.tsv')),sep='\t',row.names=FALSE,quote=FALSE)
 audits[[state]]<-data.frame(state=state,paired_donors=nlevels(meta$donor),genes_tested=nrow(tab),design_rank=qr(design)$rank,design_columns=ncol(design),target_cells=sum(meta$n_cells[meta$condition=='target']),rest_cells=sum(meta$n_cells[meta$condition=='rest']))
 cat(state,'completed',nrow(tab),'genes',nlevels(meta$donor),'donors\n');flush.console()
}
write.table(do.call(rbind,audits),file.path(base,'audit/edgeR_fit_audit.tsv'),sep='\t',row.names=FALSE,quote=FALSE)
capture.output(sessionInfo(),file=file.path(base,'audit/R_session_info.txt'))
